"""Prediction models for predictive analytics and intelligent scheduling.

Stores time-series predictions, staff scheduling recommendations, and
risk forecasts generated by the predictive analytics engine.
"""

import enum
import uuid
from datetime import date, datetime
from typing import TYPE_CHECKING, Optional

from sqlalchemy import Boolean, Date, DateTime, Float, ForeignKey, Integer, String, Text, func
from sqlalchemy import Enum as SAEnum
from sqlalchemy.dialects.postgresql import JSON, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base, TimestampMixin

if TYPE_CHECKING:
    from app.models.camera import Camera
    from app.models.organization import Organization
    from app.models.user import User
    from app.models.zone import Zone


class PredictionType(str, enum.Enum):
    """Types of predictions the system can generate."""

    FOOTFALL = "footfall"
    ALERTS = "alerts"
    OCCUPANCY = "occupancy"
    RISK = "risk"


class RiskLevel(str, enum.Enum):
    """Risk severity levels for forecast outputs."""

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class Prediction(Base):
    """A single predicted data point for a future timestamp.

    Stores the prediction value along with confidence intervals and,
    once the target time has passed, the actual observed value so that
    prediction accuracy can be measured retroactively.
    """

    __tablename__ = "predictions"

    org_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("organizations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    prediction_type: Mapped[PredictionType] = mapped_column(
        String(32),
        nullable=False,
        index=True,
    )
    camera_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("cameras.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    zone_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("zones.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    target_timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
    )
    predicted_value: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        default=0.0,
    )
    confidence_lower: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Lower bound of the 80% confidence interval",
    )
    confidence_upper: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Upper bound of the 80% confidence interval",
    )
    confidence_lower_95: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Lower bound of the 95% confidence interval",
    )
    confidence_upper_95: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Upper bound of the 95% confidence interval",
    )
    actual_value: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
        comment="Filled in after the target timestamp has passed",
    )
    model_version: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        default="hw_v1",
        server_default="hw_v1",
    )
    alert_type_name: Mapped[Optional[str]] = mapped_column(
        String(128),
        nullable=True,
        comment="For alert-type predictions, which alert type this covers",
    )

    # -- Relationships -------------------------------------------------------
    organization: Mapped["Organization"] = relationship(
        "Organization",
        lazy="selectin",
    )
    camera: Mapped[Optional["Camera"]] = relationship(
        "Camera",
        lazy="selectin",
    )
    zone: Mapped[Optional["Zone"]] = relationship(
        "Zone",
        lazy="selectin",
    )

    def __repr__(self) -> str:
        return (
            f"<Prediction(id={self.id}, type={self.prediction_type.value}, "
            f"target={self.target_timestamp}, predicted={self.predicted_value:.2f})>"
        )


class StaffSchedule(Base):
    """Hourly staff allocation recommendation for a given date.

    Generated by the predictive engine based on forecasted alert volumes
    and footfall patterns.  Each row represents one hour of the day.
    """

    __tablename__ = "staff_schedules"

    org_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("organizations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    date: Mapped[date] = mapped_column(
        Date,
        nullable=False,
        index=True,
    )
    hour: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        comment="Hour of the day (0-23)",
    )
    recommended_staff: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=1,
    )
    risk_level: Mapped[RiskLevel] = mapped_column(
        String(32),
        nullable=False,
        default=RiskLevel.LOW,
        server_default=RiskLevel.LOW.value,
    )
    predicted_alerts: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        default=0.0,
    )
    predicted_footfall: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        default=0.0,
    )
    notes: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    created_by: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )

    # -- Relationships -------------------------------------------------------
    organization: Mapped["Organization"] = relationship(
        "Organization",
        lazy="selectin",
    )
    created_by_user: Mapped[Optional["User"]] = relationship(
        "User",
        foreign_keys=[created_by],
        lazy="selectin",
    )

    def __repr__(self) -> str:
        return (
            f"<StaffSchedule(id={self.id}, date={self.date}, hour={self.hour}, "
            f"staff={self.recommended_staff}, risk={self.risk_level.value})>"
        )


class RiskForecast(Base):
    """Risk forecast for a specific camera or zone.

    Combines predicted alerts, anomaly baselines, and historical incident
    data into a single risk score (0.0 to 1.0) with a categorical level
    and a JSONB payload describing the contributing factors.
    """

    __tablename__ = "risk_forecasts"

    org_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("organizations.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    camera_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("cameras.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    zone_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("zones.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    risk_level: Mapped[RiskLevel] = mapped_column(
        String(32),
        nullable=False,
        default=RiskLevel.LOW,
        server_default=RiskLevel.LOW.value,
    )
    risk_score: Mapped[float] = mapped_column(
        Float,
        nullable=False,
        default=0.0,
        comment="Normalised risk score from 0.0 (no risk) to 1.0 (critical)",
    )
    contributing_factors: Mapped[Optional[dict]] = mapped_column(
        JSON,
        nullable=True,
        comment="Breakdown of factors contributing to the risk score",
    )
    valid_until: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
    )

    # -- Relationships -------------------------------------------------------
    organization: Mapped["Organization"] = relationship(
        "Organization",
        lazy="selectin",
    )
    camera: Mapped[Optional["Camera"]] = relationship(
        "Camera",
        lazy="selectin",
    )
    zone: Mapped[Optional["Zone"]] = relationship(
        "Zone",
        lazy="selectin",
    )

    def __repr__(self) -> str:
        return (
            f"<RiskForecast(id={self.id}, risk={self.risk_level.value}, "
            f"score={self.risk_score:.2f}, valid_until={self.valid_until})>"
        )
